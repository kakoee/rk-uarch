def test_archive_tree_rejects_repacked_wrong_member(joined: dict[str, Any]) -> None:
    root = joined["root"] / "debug/inputs"
    original = (root / "source.tar").read_bytes()
    changed = io.BytesIO()
    with (
        tarfile.open(fileobj=io.BytesIO(original)) as old,
        tarfile.open(fileobj=changed, mode="w") as new,
    ):
        for member in old:
            if member.isfile():
                stream = old.extractfile(member)
                assert stream is not None
                data = stream.read()
                if member.name == adapter.PRODUCER:
                    data = b"changed"
                    member.size = len(data)
                new.addfile(member, io.BytesIO(data))
            else:
                new.addfile(member)
    with pytest.raises(ValueError, match="archive/tree join"):
        adapter.archive_tree(
            changed.getvalue(),
            (root / "source-commit.raw").read_bytes(),
            joined["expected"]["source_commit"],
        )


@pytest.mark.parametrize("failure", [None, "nonzero", "deadline", "cleanup", "resource"])
def test_actual_transport_harness_with_mocked_guardian(
    joined: dict[str, Any],
    monkeypatch: pytest.MonkeyPatch,
    failure: str | None,
) -> None:
    from native.tools import component_container_guard as guardian
    from validation.component import runtime_campaign

    root = joined["root"] / "debug"
    wanted = json.loads((root / "expectation.json").read_bytes())
    # This test creates a second fresh output; copies only synthetic retained inputs.
    import shutil

    fresh = joined["root"] / "attempt"
    fresh.mkdir()
    shutil.copytree(root / "inputs", fresh / "inputs")
    value = ordinary.plan(joined["root"] / "prepared", fresh, "debug", joined["build"])
    (fresh / "receipts").mkdir()
    selection = helpers()

    def discover(*args: Any) -> dict[str, Any]:
        if failure == "resource":
            raise ValueError("synthetic insufficient resources")
        return resources()

    monkeypatch.setattr(runtime_campaign, "helpers", lambda: {**selection, "discover": discover})
    calls: list[str] = []

    def run(directory: Path, args: list[str], **kwargs: Any) -> dict[str, Any]:
        calls.append("run")
        assert kwargs["environment"] == ordinary.HOST_ENVIRONMENT
        assert args == value["container_argv"]
        ledger = guard_record(
            fresh, value, (root / "stdout").read_bytes(), (root / "stderr").read_bytes()
        )
        cleanup: dict[str, Any] = json.loads(
            (fresh / ledger["guardian"]["cleanup.json"]["path"]).read_bytes()
        )
        if failure == "nonzero":
            cleanup["exit_code"] = 17
        if failure == "deadline":
            cleanup["reason"] = "deadline"
        put(fresh, "container/cleanup.json", cleanup)
        put(fresh, "target/debug/uarch-engine", (root / "outputs/uarch-engine").read_bytes())
        return cleanup

    def cleanup(scope: Path) -> list[dict[str, Any]]:
        calls.append("cleanup")
        assert scope == fresh
        if failure == "cleanup":
            raise ValueError("synthetic unresolved cleanup")
        path = scope / "container/cleanup.json"
        return [json.loads(path.read_bytes())] if path.exists() else []

    monkeypatch.setattr(guardian, "run_container", run)
    monkeypatch.setattr(guardian, "cleanup", cleanup)
    receipt = harness.record_attempt(
        fresh,
        wanted["declaration"],
        {k: ordinary.LIMITS[k] for k in ("timeout_s", "stdout_bytes", "stderr_bytes")},
        lambda root, spec: ordinary.transport(root, spec, value),
    )
    assert calls[-1] == "cleanup"
    assert (fresh / "ordinary-build-receipt.json").is_file()
    assert (fresh / "transport.json").is_file()
    if failure is None:
        result = independent.consume_build(fresh, receipt, wanted)
        assert result["clean_build_success"] is True
        ordinary.verify_transport(
            fresh,
            json.loads((fresh / "transport.json").read_bytes()),
            wanted["declaration"],
            receipt,
        )
    else:
        with pytest.raises(ValueError):
            independent.consume_build(fresh, receipt, wanted)
        if failure == "resource":
            assert calls == ["cleanup"]


