def put(root: Path, name: str, value: Any) -> dict[str, str]:
    raw = value if isinstance(value, bytes) else canonical_json(value).encode()
    file = root / name
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_bytes(raw)
    return {"path": name, "byte_hash": sha256(raw)}


def git(root: Path, *args: str, data: bytes | None = None) -> bytes:
    return subprocess.check_output(["git", "-C", str(root), *args], input=data)


def resources() -> dict[str, Any]:
    policy = ordinary.resource_policy()
    result: dict[str, Any] = helpers()["select_resources"](
        [0, 1],
        [(200000, 100000)],
        8 * 1024**3,
        [(8 * 1024**3, 0)],
        reserve=policy["memory_reserve_bytes"],
        per_worker=policy["per_worker_memory_bytes"],
        tasks=1,
    )
    result.update(
        mount="/sys/fs/cgroup",
        membership="/",
        mounted_root="/",
        observed_cgroups=[
            {
                "path": "/sys/fs/cgroup",
                "cpu.max": "200000 100000",
                "memory.max": str(8 * 1024**3),
                "memory.current": 0,
            }
        ],
    )
    return result


def guard_record(root: Path, value: dict[str, Any], stdout: bytes, stderr: bytes) -> dict[str, Any]:
    owner, cid = "a" * 32, "b" * 64
    cleanup = dict(
        format="private-container-cleanup/1",
        owner=owner,
        name="u4-private-" + owner,
        container_id=cid,
        stopped=True,
        removed=True,
        exit_code=0,
        reason="completed",
    )
    rows = {
        "intent.json": dict(
            owner=owner,
            name="u4-private-" + owner,
            args=value["container_argv"],
            timeout=600,
            cap=ordinary.LIMITS["stdout_bytes"],
            stderr_cap=ordinary.LIMITS["stderr_bytes"],
            stdin=False,
            environment=ordinary.HOST_ENVIRONMENT,
        ),
        "pre-existing.json": {"containers": [{"container_id": "c" * 64}]},
        "created.json": dict(owner=owner, container_id=cid),
        "started.json": dict(container_id=cid),
        "cleanup.json": cleanup,
        "stdout": stdout,
        "stderr": stderr,
    }
    return dict(
        format="component-ordinary-build-transport/1",
        plan=value,
        resources=resources(),
        guardian={name: put(root, "container/" + name, data) for name, data in rows.items()},
        parent_cleanup=put(
            root,
            "parent-cleanup.json",
            {"format": "component-ordinary-build-parent-cleanup/1", "receipts": [cleanup]},
        ),
        failure=None,
        construction_artifacts=[put(root, "receipts/" + value["mode"] + ".map", b"synthetic map")],
    )


