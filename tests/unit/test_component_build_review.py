@pytest.mark.parametrize(
    "change",
    [
        "generated",
        "archive",
        "tools",
        "consumer",
        "command",
        "ordinary-failure",
        "cleanup",
        "resource",
        "outer-command",
        "missing-checks",
    ],
)
def test_wrong_or_stale_joins_refuse(joined: dict[str, Any], change: str) -> None:
    root, record, expected = joined["root"], joined["record"], joined["expected"]
    row = record["builds"][0]
    if change == "generated":
        # derive_declaration reseals the file; wrong semantic bytes must still refuse.
        (
            root / "debug" / adapter.SOURCE / expected["generated_identity_output_paths"][0]
        ).write_bytes(b"wrong generated identity")
    elif change == "archive":
        (root / "debug/inputs/source-commit.raw").write_bytes(b"wrong commit object")
    elif change == "tools":
        expected["tool_inputs_hash"] = sha256(b"wrong tools")
    elif change == "consumer":
        expected["consumers"]["files"] = []
        expected["consumer_hash"] = content_hash(expected["consumers"])
        record["subject"]["consumer_hash"] = expected["consumer_hash"]
    elif change in ("command", "ordinary-failure"):
        key = "expectation" if change == "command" else "receipt"
        value = json.loads((root / row[key]["path"]).read_bytes())
        if change == "command":
            value["declaration"]["argv"].append("--release")
        else:
            value["completed"] = False
        row[key] = put(root, row[key]["path"], value)
        if key == "receipt":
            outer = expected["executables"][0]["receipt"]
            data = json.loads((root / outer["path"]).read_bytes())
            data["ordinary_receipt"] = row[key]
            expected["executables"][0]["receipt"] = put(root, outer["path"], data)
    elif change == "missing-checks":
        data = json.loads((root / "checks.json").read_bytes())
        data["evidence"] = []
        record["required_checks_review"] = put(root, "checks.json", data)
    else:
        value = json.loads((root / row["transport"]["path"]).read_bytes())
        if change == "cleanup":
            value["parent_cleanup"] = put(
                root / "debug",
                "parent-cleanup.json",
                {"format": "component-ordinary-build-parent-cleanup/1", "receipts": []},
            )
        elif change == "resource":
            value["resources"]["workers"] = 2
        else:
            value["plan"]["container_argv"].append("extra")
        row["transport"] = put(root, row["transport"]["path"], value)
    with pytest.raises((ValueError, OSError, AssertionError)):
        adapter.consume_provenance(root, record, expected)


