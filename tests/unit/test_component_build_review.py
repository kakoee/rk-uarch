def test_later_construct_and_assembly_link_actual_harness(
    joined: dict[str, Any],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Exercise staging/producer links with an inert inline transport, never a build."""
    import shutil

    root, expected = joined["root"], joined["expected"]
    prepared = root / "prepared"
    shutil.copytree(root / "debug/inputs/source", prepared / "source")
    shutil.copytree(root / "debug/inputs/cache", prepared / "cache")
    for name in ("source.tar", "source-commit.raw"):
        shutil.copyfile(root / "debug/inputs" / name, prepared / name)
    put(prepared / "source", "private-component/engine.json", expected["engine"])
    consumers = dict(expected["consumers"])
    # Only inert local bytes substitute for Python snapshots; no process starts.
    consumers["external_files"] = [
        adapter.file_binding(Path("/"), str(root / "debug/inputs/python/lib.py")[1:])
    ]
    consumers["python_executable"] = adapter.file_binding(
        Path("/"), str(root / "debug/inputs/python/python")[1:]
    )

    def callback(output: Path, spec: dict[str, Any], value: dict[str, Any]) -> dict[str, Any]:
        mode = value["mode"]
        assert spec["argv"] == value["child_argv"]
        data = (root / mode / "stdout").read_bytes()
        stderr = (root / mode / "stderr").read_bytes()
        put(output, "stdout", data)
        put(output, "stderr", stderr)
        put(output, "outputs/uarch-engine", (root / mode / "outputs/uarch-engine").read_bytes())
        put(output, "transport.json", guard_record(output, value, data, stderr))
        return dict(
            exit_code=0,
            completed=True,
            timed_out=False,
            resource_failure=None,
            observed_bytes={"stdout": len(data), "stderr": len(stderr)},
            stream_complete={"stdout": True, "stderr": True},
            stream_truncated={"stdout": False, "stderr": False},
        )

    monkeypatch.setattr(ordinary, "transport", callback)
    builds = {mode: root / "first" / mode for mode in ("debug", "release")}
    for mode, output in builds.items():
        result = ordinary.construct(prepared, output, mode, consumers)
        assert result["clean_build_success"] is True
        assert result["startup_assurance"] == "not-assessed"
        assert (output / "component-build-receipt.json").is_file()
    destination = root / "assembled"
    links = ordinary.assemble_links(destination, builds)
    assert links["authority"] is None
    assert links["startup_assurance"] == "not-supplied"
    assert len(links["executables"]) == 2
    for item in links["executables"]:
        outer = json.loads((destination / item["receipt"]["path"]).read_bytes())
        assert outer["executable"] == item["executable"]
        assert outer["generated_identity"]["path"] == expected["generated_identity_output_paths"][0]
        assert not (destination / "builds" / item["mode"] / "target").exists()
    with pytest.raises(FileExistsError):
        ordinary.assemble_links(destination, builds)


